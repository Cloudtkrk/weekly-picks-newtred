def _norm(s):
    s = unicodedata.normalize("NFKC", str(s)).lower()
    return re.sub(r"[^0-9a-z぀-ヿ一-鿿]", "", s)[:30]


class Classifier:
    def __init__(self, own_rows):
        self.by_id, self.by_name = {}, {}
        shop = collections.defaultdict(collections.Counter)
        for r in own_rows:
            c = r["カテゴリ"].strip()
            self.by_id[str(r["商品ID"]).strip()] = c
            self.by_name.setdefault(_norm(r["商品名"]), c)
            shop[r["ショップ"].strip()][c] += 1
        # ④ ショップ内多数決 (70%以上を占めるカテゴリのみ採用)
        self.shop_major = {}
        for s, cc in shop.items():
            tot = sum(cc.values()); top, n = cc.most_common(1)[0]
            if tot >= 3 and n / tot >= 0.7:
                self.shop_major[s] = top

    def classify(self, pid, name, shop):
        pid, shop = str(pid).strip(), str(shop).strip()
        if pid in self.by_id:
            return self.by_id[pid], "id"
        k = _norm(name)
        if k in self.by_name:
            return self.by_name[k], "name"
        if shop in SHOP_CAT:
            base = SHOP_CAT[shop]
            if base in NO_OVERRIDE:
                return base, "shop"
            kw = self._kw(name)
            # 品揃えが分かれるショップだけ、明確なキーワードがあれば優先する
            if kw and kw != base and kw in ("食品", "美容・コスメ", "生活・雑貨", "家電"):
                return kw, "kw>shop"
            return base, "shop"
        kw = self._kw(name)
        if shop in self.shop_major:
            m = self.shop_major[shop]
            # ショップ多数決。ただしキッズ・ベビーだけはキーワードを優先 (親子ブランド対策)
            if kw == "キッズ・ベビー":
                return kw, "kw-kids"
            return m, "shopmajor"
        return (kw or "その他"), ("kw" if kw else "none")

    @staticmethod
    def _kw(name):
        for kws, c in RULES:
            for k in kws:
                if k in name:
                    return c
        return None
